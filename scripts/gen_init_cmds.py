"""gen_init_cmds.py — PlatformIO pre-build hook: embed init_cmds.txt.

Embeds the provisioning list as a flash-resident (PROGMEM) NUL-terminated
string named INIT_CMDS_DATA (with INIT_CMDS_LEN) in
include/init_cmds_data.h. When the file is absent (or empty), the header
declares an empty string so `runInitScript()` no-ops.

Source resolution (first match wins):
  1. `custom_init_cmds_file` project option on the pio env (a path relative
     to the project root, e.g. `init_cmds_Manchester.txt`)
  2. `custom_init_cmds_area` project option (e.g. `Manchester`) →
     `init_cmds_<Area>.txt`
  3. `INIT_CMDS_AREA` OS environment variable → `init_cmds_<Area>.txt`
  4. default: `init_cmds.txt`

An area that is set but whose file does not exist is a build error — a
per-area env that silently fell back to the generic list would ship the
wrong provisioning. The default path stays optional for trees without any
provisioning.

Wired from [arduino_base] extra_scripts; runs before every Arduino build.
Per-area pio envs live in area_targets.ini (see INIT_SCRIPT.md).
"""
import os
from SCons.Script import Import  # platformio provides SCons in the script env
Import("env")

def _c_escape(data: bytes) -> str:
    # group printable runs into one fragment; escape special bytes as
    # standalone 3-digit-octal fragments so sequences can never over-consume
    out, run = [], bytearray()
    for b in data:
        ch = chr(b)
        if 0x20 <= b < 0x7F and ch not in '"\\':
            run.append(b)
            continue
        if run:
            out.append('"' + run.decode("ascii") + '"')
            run = bytearray()
        if ch == '"':
            out.append('"\\""')
        elif ch == "\\":
            out.append('"\\\\"')
        else:
            out.append(f'"\\{b:03o}"')
    if run:
        out.append('"' + run.decode("ascii") + '"')
    return " ".join(out) if out else '""'

def _option(envobj, name):
    """Read a custom project option without failing when absent."""
    try:
        return envobj.GetProjectOption(name, None)
    except Exception:
        return None

def resolve_source(root, envobj=None):
    """Return (path, area) for the provisioning list to embed."""
    if envobj is not None:
        explicit = _option(envobj, "custom_init_cmds_file")
        if explicit:
            return os.path.join(root, explicit), None
        area = _option(envobj, "custom_init_cmds_area")
        if area:
            return os.path.join(root, f"init_cmds_{area}.txt"), area
    area = os.environ.get("INIT_CMDS_AREA") or None
    if area:
        return os.path.join(root, f"init_cmds_{area}.txt"), area
    return os.path.join(root, "init_cmds.txt"), None

def generate(header_path, source_path, area=None):
    if area and not os.path.isfile(source_path):
        raise SystemExit(
            f"gen_init_cmds: area {area!r} selected but {source_path} does not "
            "exist — create it (or fix custom_init_cmds_area / INIT_CMDS_AREA)")
    data = b""
    if os.path.isfile(source_path):
        data = open(source_path, "rb").read()
    body = _c_escape(data)
    src_name = os.path.basename(source_path)
    with open(header_path, "w") as f:
        f.write(f"// AUTO-GENERATED by scripts/gen_init_cmds.py from {src_name} — do not edit.\n")
        f.write("#include <pgmspace.h>\n")
        f.write(f"static const char INIT_CMDS_DATA[] PROGMEM = {body};\n")
        f.write(f"static const unsigned long INIT_CMDS_LEN = {len(data)};\n")

def _run(envobj):
    root = envobj["PROJECT_DIR"]
    source_path, area = resolve_source(root, envobj)
    generate(os.path.join(root, "include", "init_cmds_data.h"), source_path, area)

_run(env)
